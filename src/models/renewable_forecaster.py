"""Amprion solar PV and onshore-wind 24-hour forecast serving adapter.

Features are generated by the exact builders shipped with the supplied trainers.
Historical weather is used only in historical feature blocks; future covariates
come from the forecast_* columns. Missing future forecast weather suppresses a
run rather than substituting realised future weather.
"""
from __future__ import annotations

import logging

import joblib
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
import torch

from src.models.training.amprion import solar_mlp_features as solar_features
from src.models.training.amprion import solar_mlp_model
from src.models.training.amprion import Amprion_Wind_Dense as wind_features

log = logging.getLogger("amprion-renewable-forecaster")


def _path(root: Path, value: str | Path | None) -> Path | None:
    if not value:
        return None
    result = Path(value)
    return result if result.is_absolute() else root / result


def _combine_loaded(paths: list[Path], loader, *args):
    frames = []
    diagnostics = []
    for path in paths:
        if not path.is_file():
            continue
        frame, diag = loader(path, *args)
        frames.append(frame)
        diagnostics.append({"file": str(path), **diag})
    if not frames:
        raise FileNotFoundError(f"No renewable input CSV found among: {paths}")
    combined = pd.concat(frames, ignore_index=True, sort=False)
    combined["utc_timestamp"] = pd.to_datetime(combined["utc_timestamp"], utc=True, errors="coerce")
    combined = combined.dropna(subset=["utc_timestamp"]).sort_values("utc_timestamp")
    combined = combined.drop_duplicates("utc_timestamp", keep="last").reset_index(drop=True)
    return combined, diagnostics


def _check_context(frame: pd.DataFrame, origin: pd.Timestamp, history_steps: int = 672, horizon_steps: int = 96):
    # _combine_loaded() sorts and deduplicates both train/test sources once at
    # model initialisation. Do not sort/copy the full multi-year frame again on
    # every 24-hour forecast origin.
    timestamps = pd.DatetimeIndex(frame["utc_timestamp"])
    if not timestamps.is_monotonic_increasing or not timestamps.is_unique:
        raise ValueError("Renewable source frame must be sorted and have unique timestamps")
    origin = pd.Timestamp(origin)
    origin = origin.tz_localize("UTC") if origin.tzinfo is None else origin.tz_convert("UTC")
    history_pos = timestamps.get_indexer([origin])
    if history_pos[0] < history_steps - 1:
        raise ValueError(f"Not enough renewable history at origin {origin.isoformat()}")
    start = int(history_pos[0])
    hist = frame.iloc[start - history_steps + 1:start + 1].copy()
    interval = pd.Timedelta(minutes=15)
    if len(hist) != history_steps or not pd.DatetimeIndex(hist.utc_timestamp).equals(
        pd.date_range(end=origin, periods=history_steps, freq=interval, tz="UTC")
    ):
        raise ValueError("Renewable history must contain 672 continuous 15-minute observations ending at origin")
    future_ts = pd.date_range(origin + interval, periods=horizon_steps, freq=interval, tz="UTC")
    future_idx = timestamps.get_indexer(future_ts)
    if (future_idx < 0).any():
        missing = future_ts[np.flatnonzero(future_idx < 0)[:5]]
        raise ValueError(f"Renewable forecast weather coverage is incomplete; missing future timestamps: {[x.isoformat() for x in missing]}")
    future = frame.iloc[future_idx].copy()
    return hist, future, future_ts


class AmprionRenewableForecaster:
    def __init__(self, root: Path, station_id: str, config: dict[str, Any], device: torch.device | None = None):
        self.root = Path(root)
        self.station_id = station_id
        self.config = config or {}
        self.device = device or torch.device("cpu")
        self.enabled = bool(self.config.get("enabled", False))
        self.interval_minutes = 15
        self.history_steps = 672
        self.horizon_steps = 96
        self.solar_frame = pd.DataFrame()
        self.wind_frame = pd.DataFrame()
        self.solar_model = self.solar_checkpoint = None
        self.wind_model = self.wind_checkpoint = None
        self.solar_name = self.wind_name = ""
        self.solar_enabled = False
        self.wind_enabled = False
        self._renewable_time_index: dict[str, pd.DatetimeIndex] = {}
        if not self.enabled:
            return
        if int(self.config.get("interval_minutes", 15)) != 15:
            raise ValueError("Renewable models currently require 15-minute input data")
        # Models may be independently selected, trained and deployed. An
        # enabled-but-untrained optional component cannot crash demand serving.
        for kind in ("solar", "wind"):
            item = self.config.get(kind) or {}
            path = _path(self.root, item.get("checkpoint"))
            if item.get("enabled", True) and path is not None and path.is_file():
                getattr(self, f"_load_{kind}")(item)
                setattr(self, f"{kind}_enabled", True)
            elif item.get("enabled", True):
                log.warning("Renewable %s is selected but its checkpoint is unavailable: %s", kind, path)
        self.enabled = self.solar_enabled or self.wind_enabled
        # Avoid rebuilding 166k-row timestamp indexes every incoming event.
        for kind in ("solar", "wind"):
            if getattr(self, f"{kind}_enabled"):
                self._renewable_time_index[kind] = pd.DatetimeIndex(getattr(self, f"{kind}_frame")["utc_timestamp"])

    def _read_model_artifact(self, kind: str, path: Path):
        """Support native Dense, sklearn stepwise, and temporal LSTM artifacts."""
        if path.suffix.lower() == ".joblib":
            bundle = joblib.load(path)
            if bundle.get("kind") != kind or "estimator" not in bundle:
                raise ValueError(f"Invalid {kind} renewable estimator artifact")
            return bundle["estimator"], bundle
        checkpoint = torch.load(path, map_location=self.device, weights_only=False)
        if checkpoint.get("model_kind") == "renewable_lstm_v1":
            from src.models.train_renewable import RenewableLSTM
            if checkpoint.get("kind") != kind:
                raise ValueError(f"Renewable LSTM component is not {kind}")
            model = RenewableLSTM(int(checkpoint["history_features"]), int(checkpoint["future_features"]),
                                  int(checkpoint["hidden_size"])).to(self.device)
            model.load_state_dict(checkpoint["model_state_dict"])
            model.eval()
            return model, checkpoint
        if kind == "solar":
            model = solar_mlp_model.SolarMultiOutputMLP(
                input_size=int(checkpoint["input_size"]), output_size=int(checkpoint["output_size"]),
                hidden_1=int(checkpoint["hidden_1"]), hidden_2=int(checkpoint["hidden_2"]),
                dropout=float(checkpoint["dropout"]),
            ).to(self.device)
        else:
            architecture = checkpoint["architecture"]
            model = wind_features.DenseMultiOutput(
                input_size=len(checkpoint["feature_names"]), horizon=int(checkpoint["horizon"]),
                hidden_1=int(architecture["hidden_1"]), hidden_2=int(architecture["hidden_2"]),
                hidden_3=int(architecture["hidden_3"]), dropout=float(architecture["dropout"]),
            ).to(self.device)
        model.load_state_dict(checkpoint["model_state_dict"])
        model.eval()
        return model, checkpoint

    def _predict_sequence(self, kind: str, model, cp: dict, frame: pd.DataFrame) -> np.ndarray:
        from src.models.train_renewable import normalize_sequences, sequence_arrays
        hist, future, _ignored_future_target = sequence_arrays(
            kind, frame, np.asarray([self.history_steps], dtype=np.int64),
        )
        hist, future, _ = normalize_sequences(hist, future, cp["seq_stats"])
        with torch.inference_mode():
            scaled = model(torch.from_numpy(hist).to(self.device), torch.from_numpy(future).to(self.device))
            output = scaled.cpu().numpy().reshape(-1)
        return np.maximum(output * float(cp["target_std"]) + float(cp["target_mean"]), 0.0)


    def _load_solar(self, cfg: dict[str, Any]) -> None:
        paths = [_path(self.root, cfg.get("train_file")), _path(self.root, cfg.get("test_file"))]
        paths = [p for p in paths if p is not None]
        self.solar_frame, diagnostics = _combine_loaded(
            paths, solar_features.load_solar_csv, self.interval_minutes,
        )
        checkpoint_path = _path(self.root, cfg.get("checkpoint"))
        if checkpoint_path is None or not checkpoint_path.is_file():
            raise FileNotFoundError(f"Solar checkpoint not found: {checkpoint_path}")
        model, checkpoint = self._read_model_artifact("solar", checkpoint_path)
        self.solar_checkpoint, self.solar_model = checkpoint, model
        self.solar_name = str(cfg.get("model_version", "amprion-solar-mlp-v4"))
        log.info("Loaded Amprion solar model; rows=%d; coverage=%s..%s; inputs=%s",
                 len(self.solar_frame), self.solar_frame.utc_timestamp.min(), self.solar_frame.utc_timestamp.max(), diagnostics)

    def _load_wind(self, cfg: dict[str, Any]) -> None:
        paths = [_path(self.root, cfg.get("train_file")), _path(self.root, cfg.get("test_file"))]
        paths = [p for p in paths if p is not None]
        self.wind_frame, diagnostics = _combine_loaded(paths, wind_features.load_wind_data, self.interval_minutes)
        checkpoint_path = _path(self.root, cfg.get("checkpoint"))
        if checkpoint_path is None or not checkpoint_path.is_file():
            raise FileNotFoundError(f"Wind checkpoint not found: {checkpoint_path}")
        model, checkpoint = self._read_model_artifact("wind", checkpoint_path)
        self.wind_checkpoint, self.wind_model = checkpoint, model
        self.wind_name = str(cfg.get("model_version", "amprion-wind-dense-v1"))
        log.info("Loaded Amprion wind model; rows=%d; coverage=%s..%s; inputs=%s",
                 len(self.wind_frame), self.wind_frame.utc_timestamp.min(), self.wind_frame.utc_timestamp.max(), diagnostics)

    def _solar_forecast(self, origin: pd.Timestamp, issued_at: str) -> list[dict]:
        cp = self.solar_checkpoint
        hist, future, future_ts = _check_context(self.solar_frame, origin)
        target = solar_features.TARGET_COLUMN
        future[target] = 0.0  # Do not expose realised future generation to the model.
        frame = pd.concat([hist, future], ignore_index=True)
        if cp.get("model_kind") == "renewable_lstm_v1":
            values = self._predict_sequence("solar", self.solar_model, cp, frame)
            return self._records("solar", origin, future_ts, values, issued_at, self.solar_name, "forecast_cloud_and_radiation")
        x, _y, _baseline, names, diagnostics, _starts = solar_features.build_feature_matrix(
            frame, np.asarray([self.history_steps], dtype=np.int64),
            capacity_column=cp.get("capacity_column", solar_features.CAPACITY_COLUMN),
            include_solar_position=bool(cp.get("include_solar_position", False)),
            latitude=float(cp.get("latitude") or 50.966111),
            longitude=float(cp.get("longitude") or 6.805556),
            chunk_size=1, target_mean=float(cp["target_mean"]), target_std=float(cp["target_std"]),
        )
        if names != list(cp["feature_names"]) or x.shape[0] != 1 or diagnostics["valid_origins"] != 1:
            raise ValueError(f"Solar serving feature contract mismatch: {diagnostics}")
        if "estimator" in cp:
            from src.models.train_renewable import expand_origin_features
            values = np.maximum(self.solar_model.predict(expand_origin_features(x)).reshape(-1), 0.0)
            return self._records("solar", origin, future_ts, values, issued_at, self.solar_name, "forecast_cloud_and_radiation")
        if x.shape[1] != int(cp["input_size"]):
            raise ValueError("Solar serving feature dimension does not match checkpoint")
        mean = np.asarray(cp["x_mean"], dtype=np.float32)
        scale = np.asarray(cp["x_scale"], dtype=np.float32)
        scale = np.where(np.isfinite(scale) & (scale > 1e-6), scale, 1.0)
        x_scaled = (x.astype(np.float32) - mean) / scale
        with torch.inference_mode():
            scaled = self.solar_model(torch.from_numpy(x_scaled).to(self.device)).cpu().numpy().reshape(-1)
        values = np.maximum(scaled * float(cp["target_std"]) + float(cp["target_mean"]), 0.0)
        if len(values) != self.horizon_steps or not np.isfinite(values).all():
            raise RuntimeError("Solar model returned invalid forecast values")
        return self._records("solar", origin, future_ts, values, issued_at, self.solar_name, "forecast_cloud_and_radiation")

    def _wind_forecast(self, origin: pd.Timestamp, issued_at: str) -> list[dict]:
        cp = self.wind_checkpoint
        hist, future, future_ts = _check_context(self.wind_frame, origin)
        target = wind_features.TARGET_COLUMN
        future[target] = 0.0  # Do not expose realised future generation to the model.
        frame = pd.concat([hist, future], ignore_index=True)
        if cp.get("model_kind") == "renewable_lstm_v1":
            values = self._predict_sequence("wind", self.wind_model, cp, frame)
            return self._records("wind", origin, future_ts, values, issued_at, self.wind_name, "forecast_wind_speed_and_direction")
        x, _y, names, _starts, diagnostics = wind_features.build_feature_matrix(
            frame, np.asarray([self.history_steps], dtype=np.int64),
            interval_minutes=self.interval_minutes, chunk_size=1,
            future_capacity_mode=str(cp.get("future_capacity_mode", "known")),
        )
        if names != list(cp["feature_names"]) or x.shape != (1, len(names)) or diagnostics["valid_origins"] != 1:
            raise ValueError(f"Wind serving feature contract mismatch: {diagnostics}")
        if "estimator" in cp:
            from src.models.train_renewable import expand_origin_features
            values = np.maximum(self.wind_model.predict(expand_origin_features(x)).reshape(-1), 0.0)
            return self._records("wind", origin, future_ts, values, issued_at, self.wind_name, "forecast_wind_speed_and_direction")
        mean = np.asarray(cp["feature_mean"], dtype=np.float32)
        scale = np.asarray(cp["feature_std"], dtype=np.float32)
        scale = np.where(np.isfinite(scale) & (scale > 1e-6), scale, 1.0)
        x_scaled = (x.astype(np.float32) - mean) / scale
        with torch.inference_mode():
            scaled = self.wind_model(torch.from_numpy(x_scaled).to(self.device)).cpu().numpy().reshape(-1)
        values = np.maximum(scaled * float(cp["target_std"]) + float(cp["target_mean"]), 0.0)
        if len(values) != self.horizon_steps or not np.isfinite(values).all():
            raise RuntimeError("Wind model returned invalid forecast values")
        return self._records("wind", origin, future_ts, values, issued_at, self.wind_name, "forecast_wind_speed_and_direction")

    def _records(self, kind: str, origin: pd.Timestamp, timestamps: pd.DatetimeIndex, values: np.ndarray,
                 issued_at: str, model_version: str, weather_mode: str) -> list[dict]:
        origin_text = pd.Timestamp(origin).isoformat()
        run_id = f"{self.station_id}|{kind}|{origin_text}|{model_version}"
        return [{
            "station_id": self.station_id, "generation_type": kind,
            "forecast_issued_at_utc": issued_at, "forecast_origin_utc": origin_text,
            "forecast_run_id": run_id, "forecast_timestamp_utc": ts.isoformat(),
            "horizon_step": int(step), "predicted_generation_mwh": float(value),
            "model_version": model_version, "weather_mode": weather_mode,
        } for step, (ts, value) in enumerate(zip(timestamps, values), start=1)]

    def observations_at(self, timestamp: pd.Timestamp) -> list[dict]:
        """Actual generation exactly at the replayed observation timestamp.

        The model feature tables currently only extend through the configured
        train/test period. Return no fake actuals beyond their coverage.
        """
        timestamp = pd.Timestamp(timestamp)
        timestamp = timestamp.tz_localize("UTC") if timestamp.tzinfo is None else timestamp.tz_convert("UTC")
        found = []
        for kind, target in (("solar", "Photovoltaics [MWh]"), ("wind", "Wind onshore [MWh]")):
            if not getattr(self, f"{kind}_enabled", False):
                continue
            frame = getattr(self, f"{kind}_frame")
            if frame.empty or target not in frame.columns:
                continue
            # DatetimeIndex is pre-sorted by the corresponding feature loader.
            times = self._renewable_time_index.get(kind)
            if times is None:
                times = pd.DatetimeIndex(frame["utc_timestamp"])
            index = times.get_indexer([timestamp])[0]
            if index < 0:
                continue
            value = pd.to_numeric(pd.Series([frame.iloc[index][target]]), errors="coerce").iloc[0]
            if pd.notna(value):
                found.append({
                    "station_id": self.station_id, "generation_type": kind,
                    "utc_timestamp": timestamp.isoformat(),
                    "actual_generation_mwh": float(value),
                    "source": "registered_historical_replay",
                })
        return found

    def forecast_at(self, origin: pd.Timestamp) -> list[dict]:
        if not self.enabled:
            return []
        origin = pd.Timestamp(origin)
        origin = origin.tz_localize("UTC") if origin.tzinfo is None else origin.tz_convert("UTC")
        issued_at = pd.Timestamp.now(tz="UTC").isoformat()
        records: list[dict] = []
        for name, method in (("solar", self._solar_forecast), ("wind", self._wind_forecast)):
            if not getattr(self, f"{name}_enabled", False):
                continue
            try:
                records.extend(method(origin, issued_at))
            except Exception as exc:
                # Renewable output is an independent enrichment. A solar/wind
                # failure must not stop the primary demand forecasting stream.
                log.exception("Skipping %s renewable forecast at %s: %s", name, origin.isoformat(), exc)
        return records
